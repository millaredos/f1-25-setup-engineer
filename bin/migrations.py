"""Embed versioned SQL in PHP so existing updaters can distribute migrations."""
from pathlib import Path
import argparse
import hashlib
import re

ROOT = Path(__file__).resolve().parent.parent


def statements(source):
    # Explicit boundaries avoid treating semicolons inside SQL strings as separators.
    return [part.strip() for part in re.split(r"^-- statement\s*$", source, flags=re.M) if part.strip()]


def build(check=False):
    entries = []
    for schema in sorted((ROOT / "data/migrations").glob("*.schema.sql")):
        identifier = schema.name.removesuffix(".schema.sql")
        data = schema.with_name(identifier + ".data.sql")
        ddl, dml = schema.read_text(encoding="utf-8"), data.read_text(encoding="utf-8")
        digest = hashlib.sha256((ddl + "\0" + dml).encode()).hexdigest()
        quote = lambda s: "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"
        parts = [f"    {quote(identifier)} => [", f"        'checksum' => '{digest}',"]
        for kind, source in [("schema", ddl), ("data", dml)]:
            parts.append(f"        '{kind}' => [")
            parts.extend("            " + quote(sql) + "," for sql in statements(source))
            parts.append("        ],")
        parts.append("    ],")
        entries.append("\n".join(parts))
    output = "<?php\n// Generated by bin/migrations.py; edit data/migrations/*.sql.\nreturn [\n" + "\n".join(entries) + "\n];\n"
    target = ROOT / "src/migration_catalog.php"
    if check:
        if not target.exists() or target.read_bytes() != output.encode():
            raise ValueError("SQL migration catalog is stale; run python bin/migrations.py")
    else:
        target.write_bytes(output.encode())


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    build(**vars(parser.parse_args()))
