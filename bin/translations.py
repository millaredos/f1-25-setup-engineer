"""Validate PO sources and generate deterministic PHP catalogs (development only)."""
from pathlib import Path
import argparse
import re
import json
import polib

ROOT = Path(__file__).resolve().parent.parent
PLACEHOLDER = re.compile(r"\{[a-zA-Z][a-zA-Z0-9_]*\}")
STRING = r"'((?:\\.|[^'\\])*)'"


def literal(value):
    return value.replace("\\'", "'").replace('\\\\', '\\')


def source_messages():
    """The app uses literal single-quoted messages; dynamic catalog/error fields are explicit."""
    entries = {}
    for path in [*ROOT.glob('src/*.php'), *ROOT.glob('public_html/*.php'), *ROOT.glob('public_html/assets/*.js')]:
        if path.name.startswith('locale_'):
            continue
        text = path.read_text(encoding='utf-8')
        for match in re.finditer(r'\b(?:t|tr)\(' + STRING, text):
            entries.setdefault(literal(match[1]), '')
        for match in re.finditer(r'\btn\(' + STRING + r',\s*' + STRING, text):
            entries[literal(match[1])] = literal(match[2])
        if path.name in ['Updates.php', 'Updater.php', 'Store.php', 'InstallationState.php', 'update.php']:
            for match in re.finditer(r"'(?:\\.|[^'\\])*'", text):
                value = literal(match[0][1:-1])
                if value.endswith('.') and ' ' in value and not value.startswith(('/', '~')):
                    entries.setdefault(value, '')
    # Messages supplied through a variable, rather than a literal t() argument.
    for value in ['Inicio', 'Circuito y referencia', 'Taller', 'Pruebas', 'Versiones', 'Sesiones', 'Correcto', 'Pendiente', 'Alpha', 'Estable', 'Nombre', 'Notas', 'Fuente', 'Circuito', 'Trazado', 'Carga', 'Resumen', 'Superficie']:
        entries.setdefault(value, '')
    fields = {'notice', 'category', 'name', 'phase', 'what', 'up', 'down', 'up_label', 'down_label', 'note', 'label', 'check', 'why', 'cost', 'combined'}
    def visit(data, parent=''):
        if isinstance(data, dict):
            for key, value in data.items():
                if isinstance(value, str) and key in fields:
                    entries.setdefault(value, '')
                else:
                    visit(value, key)
        elif isinstance(data, list):
            for value in data:
                if parent in ['up_imp', 'down_imp'] and isinstance(value, list):
                    entries.setdefault(value[1], '')
                else:
                    visit(value, parent)
    for path in [ROOT / 'data/parameters.json', ROOT / 'data/symptoms.json']:
        visit(json.loads(path.read_text(encoding='utf-8')))
    return entries


def extract():
    source = ROOT / 'languages/es.po'
    po = polib.pofile(str(source), encoding='utf-8')
    messages = source_messages()
    for message, plural in sorted(messages.items()):
        entry = po.find(message)
        if entry is None:
            entry = polib.POEntry(msgid=message, msgid_plural=plural)
            po.append(entry)
    for entry in po:
        entry.obsolete = entry.msgid not in messages
    po.save()


def php_string(value):
    return "'" + value.replace('\\', '\\\\').replace("'", "\\'") + "'"


def compile_catalog(source):
    po = polib.pofile(str(source), encoding="utf-8", check_for_duplicates=True)
    if po.metadata.get("Language") != source.stem:
        raise ValueError(f"{source}: language header does not match filename")
    if po.metadata.get("Plural-Forms") != "nplurals=2; plural=(n != 1);":
        raise ValueError(f"{source}: unsupported plural rule; update the PHP/JS runtime explicitly")
    messages, plurals = {}, {}
    for entry in po:
        if entry.obsolete:
            continue
        if entry.msgctxt:
            raise ValueError(f"{source}: contexts require explicit runtime support")
        if 'fuzzy' in entry.flags:
            raise ValueError(f"{source}: review fuzzy translation: {entry.msgid}")
        forms = [entry.msgstr] if not entry.msgid_plural else [entry.msgstr_plural.get(i, '') for i in range(2)]
        if not all(forms):
            raise ValueError(f"{source}: incomplete translation: {entry.msgid}")
        originals = [entry.msgid] if not entry.msgid_plural else [entry.msgid, entry.msgid_plural]
        for original, translated in zip(originals, forms):
            if sorted(PLACEHOLDER.findall(original)) != sorted(PLACEHOLDER.findall(translated)):
                raise ValueError(f"{source}: mismatched placeholders: {entry.msgid}")
            if '\x00' in translated:
                raise ValueError(f"{source}: null byte in translation")
        if entry.msgid_plural:
            plurals[entry.msgid] = forms
        else:
            messages[entry.msgid] = forms[0]
    lines = ["<?php", "declare(strict_types=1);", "// Generated by bin/translations.py. Edit languages/*.po instead.", "return [", "    'messages' => ["]
    lines += [f"        {php_string(key)} => {php_string(value)}," for key, value in sorted(messages.items())]
    lines += ["    ],", "    'plurals' => ["]
    lines += [f"        {php_string(key)} => [{php_string(forms[0])}, {php_string(forms[1])}]," for key, forms in sorted(plurals.items())]
    return '\n'.join(lines + ["    ],", "];", ""])


def build(check=False):
    catalogs = sorted((ROOT / 'languages').glob('*.po'))
    if not catalogs:
        raise ValueError('No PO catalogs found')
    for source in catalogs:
        if not re.fullmatch(r'[a-z]{2}(?:_[A-Z]{2})?', source.stem):
            raise ValueError('Invalid catalog language')
        content = compile_catalog(source)
        po = polib.pofile(str(source), encoding='utf-8')
        found = {entry.msgid: entry.msgid_plural for entry in po if not entry.obsolete}
        for message, plural in source_messages().items():
            if found.get(message) != plural:
                raise ValueError(f'{source}: missing/outdated message: {message}; run --extract and translate it')
        target = ROOT / 'src' / f'locale_{source.stem}.php'
        if check:
            if not target.exists() or target.read_text(encoding='utf-8') != content:
                raise ValueError(f'{target.name} is stale; run python bin/translations.py')
        else:
            target.write_text(content, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--extract', action='store_true')
    args = parser.parse_args()
    if args.extract:
        extract()
    else:
        build(check=args.check)
