/* Pruebas del sitio local propio. Playwright solo es herramienta de desarrollo. */
const { chromium } = require(process.env.F125_PLAYWRIGHT || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
  const browser = await chromium.launch({ ...(process.env.F125_TEST_BROWSER === 'chromium' ? {} : { channel: 'msedge' }), headless: true });
  const baseURL = process.env.F125_TEST_URL || 'http://127.0.0.1:8125/';
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1080 }, acceptDownloads: true });
    const installerResponse = await context.request.get(new URL('install.php', baseURL).href, { maxRedirects: 0 });
    assert.equal(installerResponse.status(), 302, 'sitio instalado devuelve el instalador al inicio');
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    page.on('dialog', (dialog) => dialog.accept());
    const response = await page.goto(baseURL);
    assert.match(response.headers()['content-security-policy'], /style-src 'self'/);
    await page.locator('#settings input').first().waitFor({ state: 'attached' });
    const nav = async (section) => { await page.locator(`.app-nav a[href="#${section}"]`).click(); };
    assert.equal(await page.locator('[data-page="inicio"]').isVisible(), true);
    assert.equal(await page.locator('#editor').isVisible(), false);
    assert.match(await page.locator('.driver').innerText(), new RegExp(fs.readFileSync(path.join(__dirname, '../src/VERSION'), 'utf8').trim().replace(/[.*+?^${}()|[\]\\]/g, '\\$&')));
    assert.doesNotMatch(await page.locator('.driver').innerText(), /MOZA/);
    await nav('circuito');
    assert.equal(await page.locator('#settings input').count(), 20);
    assert.equal(await page.locator('style,[style]').count(), 0);
    assert.equal(await page.locator('#value-ala_del').inputValue(), '');
    await page.locator('#example').click();
    await page.waitForFunction(() => document.querySelector('#change-count').textContent === '0 de 20 modificados');
    await nav('taller');
    await page.locator('#value-ala_del').fill('22');
    await page.locator('#value-ala_tra').fill('24');
    await page.waitForFunction(() => document.querySelector('#change-count').textContent === '2 de 20 modificados');
    assert.match(await page.locator('#summary').innerText(), /Menos carga delantera/);
    assert.match(await page.locator('#summary').innerText(), /Más agarre/);
    await page.locator('#value-cam_del').fill('-3.5');
    await page.waitForFunction(() => document.querySelector('#change-count').textContent === '3 de 20 modificados');
    assert.match(await page.locator('[data-parameter="cam_del"] .theory').innerText(), /Caída más negativa/);
    await nav('pruebas');
    await page.locator('#symptom').selectOption('rear-exit');
    assert.match(await page.locator('#advice').innerText(), /No hay solución universal/);
    await nav('taller');
    await page.locator('#value-barra_tra').fill('1');
    await nav('pruebas');
    assert.match(await page.locator('#advice').innerText(), /Ya estás en el límite/);
    await nav('versiones');
    const downloadPromise = page.waitForEvent('download');
    await page.locator('#export').click();
    const download = await downloadPromise;
    const exported = JSON.parse(fs.readFileSync(await download.path(), 'utf8'));
    assert.equal(exported.reference.ala_del, 23);
    assert.equal(exported.current.ala_del, 22);
    assert.equal(exported.current.cam_del, -3.5);
    assert.equal(exported.referenceSource, 'capture');
    await page.reload();
    await page.locator('#recover').waitFor();
    await page.locator('#recover').click();
    await page.waitForFunction(() => document.querySelector('#value-ala_del').value === '22');
    assert.match(await page.locator('#reference-label').innerText(), /capturas/);
    await nav('circuito');
    await page.locator('#open-setup').click();
    const legacy = fs.readFileSync(path.join(__dirname, 'fixtures/legacy-setup.json'), 'utf8');
    await page.locator('#json-input').fill(legacy);
    await page.locator('#validate-import').click();
    await page.locator('#apply-import').waitFor();
    assert.equal(await page.locator('.preview-values tr').count(), 21);
    await page.locator('#apply-import').click();
    assert.equal(await page.locator('#value-ala_del').inputValue(), '23');
    await nav('taller');
    await page.locator('#restore').click();
    assert.equal(await page.locator('#value-ala_tra').inputValue(), '23');
    await nav('circuito');
    await page.locator('#open-circuit').click();
    const fixture = { format: 'f125-circuit', schemaVersion: 1, circuit: { id: 'test-browser', name: '<img src=x onerror=alert(1)>', downforce: 'mixed', summary: 'Solo prueba, no circuito real', sources: [{ title: 'Prueba', url: 'https://example.com', accessedAt: '2026-11-04' }] } };
    await page.locator('#json-input').fill(JSON.stringify(fixture));
    await page.locator('#validate-import').click();
    await page.locator('#apply-import').waitFor();
    assert.equal(await page.locator('#import-preview img').count(), 0);
    assert.match(await page.locator('#import-preview').innerText(), /<img/);
    await page.locator('.dialog-close').click();
    const circuitSetup = { ...exported, circuit: { ...fixture.circuit, name: 'Circuito ficticio de prueba' } };
    await nav('circuito');
    await page.locator('#open-setup').click();
    await page.locator('#json-input').fill(JSON.stringify(circuitSetup));
    await page.locator('#validate-import').click();
    await page.locator('#apply-import').waitFor();
    await page.locator('#apply-import').click();
    assert.equal(await page.locator('#circuit').inputValue(), 'test-browser');
    await nav('circuito');
    await page.locator('#open-setup').click();
    await page.locator('#json-input').fill(legacy);
    await page.locator('#validate-import').click();
    await page.locator('#apply-import').waitFor();
    assert.match(await page.locator('#import-preview').innerText(), /Al aplicar lo asociarás/);
    await page.locator('#apply-import').click();
    assert.equal(await page.locator('#circuit').inputValue(), 'test-browser', 'importar legado conserva asociación explícita');
    const csrfCheck = await context.request.post(new URL('api.php?action=compare', baseURL).href, { data: {} });
    assert.equal(csrfCheck.status(), 403);
    const token = await page.evaluate(async () => (await (await fetch('api.php?action=bootstrap')).json()).csrf);
    const invalid = await context.request.post(new URL('api.php?action=import-setup', baseURL).href, { headers: { 'X-CSRF-Token': token }, data: { format: 'desconocido' } });
    assert.equal(invalid.status(), 422);
    await nav('taller');
    await page.locator('#value-ala_del').fill('22');
    await page.locator('#value-ala_tra').fill('24');
    await nav('pruebas');
    await page.locator('#symptom').selectOption('rear-fast');
    await page.waitForFunction(() => document.querySelector('#change-count').textContent === '2 de 20 modificados');
    await nav('taller');
    const destination = process.env.F125_SCREENSHOTS;
    for (const width of [1440, 768, 390]) {
      await page.setViewportSize({ width, height: 1050 });
      assert.equal(await page.locator('.driver').isVisible(), true, 'versión visible también en móvil');
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, `sin desbordamiento en ${width}px`);
      if (destination) { fs.mkdirSync(destination, { recursive: true }); await page.screenshot({ path: path.join(destination, `taller-${width}.png`), fullPage: true }); }
    }
    await nav('inicio');
    await page.locator('[data-page="inicio"]').waitFor({ state: 'visible' });
    for (const width of [1440, 768, 390]) {
      await page.setViewportSize({ width, height: 1050 });
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, `home fits ${width}px`);
      if (destination) await page.screenshot({ path: path.join(destination, `inicio-${width}.png`), fullPage: true });
    }
    assert.deepEqual(errors, []);
    await page.locator('.app-nav a[href="options.php"]').click();
    await page.locator('#update-channel').selectOption('alpha');
    await page.getByRole('button', { name: 'Save options' }).click();
    assert.equal(await page.locator('#update-channel').inputValue(), 'alpha');
    assert.equal(await page.locator('style,[style]').count(), 0);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'options fit mobile');
    if (destination) await page.screenshot({ path: path.join(destination, 'options-390.png'), fullPage: true });
    await page.getByRole('link', { name: 'Check for updates' }).click();
    assert.equal(await page.locator('#current-channel').innerText(), 'Alpha');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'updates fit mobile');
    if (destination) await page.screenshot({ path: path.join(destination, 'updates-390.png'), fullPage: true });
    await page.getByRole('link', { name: 'Options', exact: true }).click();
    await page.locator('#update-channel').selectOption('release');
    await page.getByRole('button', { name: 'Save options' }).click();
    console.log('OK: navegador real, veinte controles, comparación, caídas, síntomas, exportación, recuperación, importación, XSS, CSRF y responsive.');
    await context.close();
  } finally { await browser.close(); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
