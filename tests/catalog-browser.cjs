const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.F125_PLAYWRIGHT || 'playwright');

(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.F125_TEST_BROWSER === 'chromium' ? {} : { channel: 'msedge' }) });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    page.on('dialog', d => d.accept());
    await page.route('**/api.php?action=update-status', r => r.fulfill({ json: { known: true, newer: false } }));
    await page.goto(process.env.F125_TEST_URL + '#circuito');
    await page.locator('#circuit option').nth(25).waitFor({ state: 'attached' });
    assert.equal(await page.locator('#circuit option').count(), 26);
    const bootstrap = await (await page.request.get(process.env.F125_TEST_URL + 'api.php?action=bootstrap')).json();
    assert.deepEqual(Object.keys(bootstrap.circuitDescriptions).sort(), bootstrap.gameCatalog.circuits.map(c => c.id).sort());
    await page.locator('#circuit').selectOption('australia-albert-park');
    assert.equal(await page.locator('#saved').inputValue(), 'preset:3');
    assert.match(await page.locator('#circuit-card').innerText(), /5,278 km/);
    await page.locator('.app-nav a[href="#taller"]').click();
    await page.locator('#new-setup').click();
    await page.locator('#load-season').selectOption('2025');
    await page.locator('#load-circuit').selectOption('australia-albert-park');
    await page.locator('#apply-saved-setup').click();
    assert.equal(await page.locator('#value-ala_del').inputValue(), '');
    await page.locator('#setup-title').fill('Incomplete');
    await page.locator('#save').click();
    await page.getByRole('status').filter({hasText:'Completa los veinte valores'}).waitFor();
    await page.locator('#new-setup').click();
    await page.locator('#unsaved-dialog').waitFor({state:'visible'});
    await page.locator('#unsaved-discard').click();
    await page.locator('#load-season').selectOption('2026');
    await page.locator('#load-circuit').selectOption('australia-albert-park');
    await page.locator('#apply-saved-setup').click();
    assert.equal(await page.locator('#value-ala_del').inputValue(), '25');
    await page.locator('#setup-title').fill('Albert Park personal');
    await page.locator('#value-ala_del').fill('27');
    await page.locator('[data-group-note="aero"]').fill('Test front wing');
    const downloadPromise = page.waitForEvent('download');
    await page.locator('#export-workshop').click();
    const exported = JSON.parse(fs.readFileSync(await (await downloadPromise).path(), 'utf8'));
    assert.equal(exported.current.ala_del, 27);
    assert.equal(exported.groupNotes.aero, 'Test front wing');
    await page.locator('#save').click();
    await page.getByRole('status').filter({hasText:'Reglaje guardado.'}).waitFor();
    await page.locator('#value-ala_del').fill('28');
    await page.locator('.app-nav a[href="#circuito"]').click();
    await page.locator('#unsaved-dialog').waitFor({state:'visible'});
    await page.locator('#unsaved-cancel').click();
    assert.equal(await page.locator('#value-ala_del').inputValue(), '28');
    await page.locator('.app-nav a[href="#circuito"]').click();
    await page.locator('#unsaved-dialog').waitFor({state:'visible'});
    await page.locator('#unsaved-discard').click();
    await page.locator('.app-nav a[href="#taller"]').click();
    await page.locator('#open-saved-setup').click();
    await page.locator('#load-season').selectOption('2026');
    await page.locator('#load-circuit').selectOption('australia-albert-park');
    await page.locator('#load-setup').selectOption({index:1});
    await page.locator('#apply-saved-setup').click();
    await page.locator('#saved-setup-dialog').waitFor({state:'hidden'});
    assert.equal(await page.locator('#value-ala_del').inputValue(), '27');
    assert.equal(await page.locator('[data-group-note="aero"]').inputValue(), 'Test front wing');
    await page.locator('#value-ala_del').fill('26');
    await page.locator('#save').click();
    await page.waitForFunction(() => document.querySelector('#value-ala_del').closest('article').textContent.includes('Inicial: 26'));
    const stored = await (await page.request.get(process.env.F125_TEST_URL + 'api.php?action=bootstrap')).json();
    assert.equal(stored.setups.length, 1, 'update retains one saved setup');
    await page.locator('#delete-setup').click();
    await page.getByRole('status').filter({hasText:'Reglaje eliminado.'}).waitFor();
    assert.equal((await (await page.request.get(process.env.F125_TEST_URL + 'api.php?action=bootstrap')).json()).setups.length, 0);
    for (const width of [1440, 390]) {
      await page.setViewportSize({width, height:1000});
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
      if (process.env.F125_SCREENSHOTS) await page.screenshot({path:path.join(process.env.F125_SCREENSHOTS, `workshop-${width}.png`), fullPage:true});
    }
    assert.deepEqual(errors, []);
    console.log('OK: catalog, preset, empty setup, save, edit, group notes, export, navigation and delete with isolated storage.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
