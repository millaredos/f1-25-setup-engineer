<?php
declare(strict_types=1);

/** Generate the distributable migration catalog from immutable SQL sources. */
function migrationCatalog(string $root): string
{
    $files = glob($root . '/data/migrations/*.schema.sql');
    if ($files === false) {
        throw new RuntimeException('Cannot list migration sources.');
    }
    sort($files, SORT_STRING);
    $entries = [];
    foreach ($files as $schemaPath) {
        $id = basename($schemaPath, '.schema.sql');
        $dataPath = $root . '/data/migrations/' . $id . '.data.sql';
        $schema = file_get_contents($schemaPath);
        $data = file_get_contents($dataPath);
        if ($schema === false || $data === false) {
            throw new RuntimeException('Cannot read migration ' . $id);
        }
        $quote = static fn (string $value): string => "'" . str_replace(['\\', "'"], ['\\\\', "\\'"], $value) . "'";
        $lines = ['    ' . $quote($id) . ' => [', "        'checksum' => '" . hash('sha256', $schema . "\0" . $data) . "',"];
        foreach (['schema' => $schema, 'data' => $data] as $kind => $source) {
            $lines[] = "        '" . $kind . "' => [";
            $statements = preg_split('/^-- statement\s*$/m', $source);
            if ($statements === false) {
                throw new RuntimeException('Cannot split migration ' . $id);
            }
            foreach ($statements as $statement) {
                $statement = trim($statement);
                if ($statement !== '') {
                    $lines[] = '            ' . $quote($statement) . ',';
                }
            }
            $lines[] = '        ],';
        }
        $lines[] = '    ],';
        $entries[] = implode("\n", $lines);
    }
    return "<?php\ndeclare(strict_types=1);\n// Generated by dev/bin/migrations.php; edit data/migrations/*.sql.\nreturn [\n"
        . implode("\n", $entries) . "\n];\n";
}

$root = dirname(__DIR__, 2);
$target = $root . '/src/migration_catalog.php';
try {
    $output = migrationCatalog($root);
    if (in_array('--check', $argv, true)) {
        if (!is_file($target) || file_get_contents($target) !== $output) {
            throw new RuntimeException('SQL migration catalog is stale; run php dev/bin/migrations.php');
        }
    } elseif (file_put_contents($target, $output) === false) {
        throw new RuntimeException('Cannot write migration catalog.');
    }
} catch (Throwable $error) {
    fwrite(STDERR, $error->getMessage() . PHP_EOL);
    exit(1);
}
