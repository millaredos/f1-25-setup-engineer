<?php
declare(strict_types=1);

/** Parse the supported PO subset strictly; no eval, gettext extension or external runtime is needed. */
function readPo(string $path): array
{
    $lines = file($path, FILE_IGNORE_NEW_LINES);
    if ($lines === false) { throw new RuntimeException('Cannot read PO source.'); }
    $entries = [];
    $entry = [];
    $active = null;
    $flush = static function () use (&$entry, &$entries, &$active): void {
        if ($entry !== []) {
            if (!isset($entry['msgid']) || isset($entry['msgctxt']) || isset($entry['fuzzy'])) { throw new RuntimeException('Incomplete, contextual or fuzzy PO entry.'); }
            $key = $entry['msgid'];
            if (array_key_exists($key, $entries)) { throw new RuntimeException('Duplicate PO message.'); }
            $entries[$key] = $entry;
        }
        $entry = [];
        $active = null;
    };
    foreach (array_merge($lines, ['']) as $line) {
        if (trim($line) === '') { $flush(); continue; }
        if (str_starts_with($line, '#~')) { continue; }
        if (str_starts_with($line, '#')) { if (str_starts_with($line, '#,') && str_contains($line, 'fuzzy')) { $entry['fuzzy'] = true; } continue; }
        if (preg_match('/^(msgid_plural|msgid|msgctxt|msgstr(?:\[[01]\])?)\s+(".*")$/D', $line, $match)) {
            $active = $match[1];
            if (array_key_exists($active, $entry)) { throw new RuntimeException('Repeated PO field.'); }
            $entry[$active] = poString($match[2]);
        } elseif (preg_match('/^".*"$/D', $line) && $active !== null) {
            $entry[$active] .= poString($line);
        } else { throw new RuntimeException('Unsupported PO syntax.'); }
    }
    return $entries;
}

/** Decode quoted PO strings without executing PHP or accepting unknown escapes. */
function poString(string $literal): string
{
    $value = substr($literal, 1, -1);
    $decoded = preg_replace_callback('/\\\\(.)/s', static function (array $match): string {
        $map = ['n' => "\n", 'r' => "\r", 't' => "\t", '"' => '"', '\\' => '\\'];
        if (!array_key_exists($match[1], $map)) { throw new RuntimeException('Unsupported PO escape.'); }
        return $map[$match[1]];
    }, $value);
    if ($decoded === null || !preg_match('//u', $decoded) || str_contains($decoded, "\0")) { throw new RuntimeException('Invalid PO string.'); }
    return $decoded;
}

/** Compile editable PO sources into data-only PHP catalogs, rejecting missing forms and placeholders. */
function compilePo(string $path, string $language): string
{
    $entries = readPo($path);
    $header = $entries['']['msgstr'] ?? '';
    if (!str_contains($header, 'Language: ' . $language . "\n") || !str_contains($header, 'Plural-Forms: nplurals=2; plural=(n != 1);')) { throw new RuntimeException('Language or plural rule mismatch.'); }
    $messages = [];
    $plurals = [];
    unset($entries['']);
    ksort($entries, SORT_STRING);
    foreach ($entries as $id => $entry) {
        $plural = isset($entry['msgid_plural']);
        $forms = $plural ? [$entry['msgstr[0]'] ?? '', $entry['msgstr[1]'] ?? ''] : [$entry['msgstr'] ?? ''];
        foreach ($forms as $index => $translation) {
            if ($translation === '') { throw new RuntimeException('Incomplete translation: ' . $id); }
            preg_match_all('/\{[A-Za-z][A-Za-z0-9_]*\}/', $index === 1 ? $entry['msgid_plural'] : $id, $sourceTokens);
            preg_match_all('/\{[A-Za-z][A-Za-z0-9_]*\}/', $translation, $targetTokens);
            sort($sourceTokens[0]); sort($targetTokens[0]);
            if ($sourceTokens[0] !== $targetTokens[0]) { throw new RuntimeException('Translation placeholders differ.'); }
        }
        if ($plural) { $plurals[$id] = $forms; } else { $messages[$id] = $forms[0]; }
    }
    $export = preg_replace('/[ \t]+$/m', '', var_export(['messages' => $messages, 'plurals' => $plurals], true));
    return "<?php\ndeclare(strict_types=1);\n// Generated by dev/bin/translations.php from languages/*.po.\nreturn " . $export . ";\n";
}

if (realpath($_SERVER['SCRIPT_FILENAME'] ?? '') === __FILE__) {
    try {
        $root = dirname(__DIR__, 2);
        $check = in_array('--check', $argv, true);
        foreach (glob($root . '/languages/*.po') as $path) {
            $language = basename($path, '.po');
            if (!preg_match('/^[a-z]{2}(?:_[A-Z]{2})?$/D', $language)) { throw new RuntimeException('Invalid language identifier.'); }
            $result = compilePo($path, $language);
            $directory = $root . '/src/Translation';
            if (!is_dir($directory) && !mkdir($directory, 0755, true)) { throw new RuntimeException('Cannot prepare generated catalogs.'); }
            $target = $directory . '/catalog_' . $language . '.php';
            if ($check) { if (!is_file($target) || file_get_contents($target) !== $result) { throw new RuntimeException('Generated catalog is stale.'); } }
            elseif (file_put_contents($target, $result) !== strlen($result)) { throw new RuntimeException('Cannot write catalog.'); }
        }
    } catch (Throwable $error) { fwrite(STDERR, $error->getMessage() . PHP_EOL); exit(1); }
}
